#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAX_STUDENTS 50
#define NAME_LEN     50

/*
 * 二分查找的本质是分段函数的分界点搜索。
 * 所有的变形（闭、左开、右开）都是为了在离散的索引空间内，通过维护一个包含潜在答案的不变量区间，强制搜索空间在每一轮迭代中产生单调收缩，最终让区间坍缩至目标分界点。
 *
 * 二分查找的每一轮迭代，本质上是在做两件事之一：
 * 彻底排除
 *   当 `mid` 指向的元素被证明**不符合条件**时，该位置及该侧的所有元素被永久移除出候选集合。
 *   在 `[lo, hi]` 中：`lo = mid + 1` 或 `hi = mid - 1`。
 *   在 `[lo, hi)` 中：`lo = mid + 1` 或 `hi = mid`（因为 hi 本身不包含在内）。
 *   在 `(lo, hi]` 中：`lo = mid` 或 `hi = mid - 1`（因为 lo 本身不包含在内）。
 * 建立保底
 *   如果 mid 符合条件，它必须留在下一轮的搜索空间里。因为它可能是最终答案。
 *   在 `[lo, hi)` 中：一旦 array[mid] == target，直接返回 mid。不需要保底，直接命中。
 *   在 `[lo, hi)` 中：寻找第一个符合条件的位置
 *   如果 `mid` 符合条件（如 `array[mid] >= target`），则执行 `hi = mid`。
 *       此时搜索空间收缩为 `[lo,mid)`。
 *          理解难点：既然新区间是 `[lo, mid)`，不包含 `mid`，为什么说“保住了”它？
 *          逻辑：在这一轮，`mid` 确实被放在了区间外，但它成为了**新的边界线**。
 *              如果随后在 `[lo, mid)` 中再也找不到符合条件的元素，循环结束时 `lo` 会一直向右递增，最终停在 `mid` 这个位置。
 *          结论：当前的 `mid` 是一个临时标尺，我们去左边找更小的标尺；找不到，它就是答案。
 *   在 `(lo, hi]` 中：寻找最后一个符合条件的位置
 *   如果 `mid` 符合条件（如 `array[mid] <= target`），则执行 `lo = mid`。
 *       此时搜索空间收缩为 `(mid,hi]`。
 *          逻辑：同理，新区间变为 `(mid, hi]`。虽然 `mid` 变成了开区间边界，但它已经排除了左侧所有干扰。
 *          收敛行为：如果 `(mid, hi]` 中没有更靠右的符合条件者，`hi` 会向左缩减，最终与 `lo` 会师在 `mid` 指向的那个索引。
 *
 * 通过不断排除不可能的选项，使“可能存在目标的区间”最终坍缩为一个点。
 * 小结一下, 我们将数组长度设为 $N$，目标设为 $T$。
 *
 * 区间类型对照表：
 * | **区间类型**            | **初始范围** | **退出条件** | **寻找第一个 ≥T 的更新**                  | **寻找最后一个 ≤T 的更新**                |
 * | ----------------------- | ------------ | ------------ | ----------------------------------------- | ----------------------------------------- |
 * | **闭区间 `[lo, hi]`**   | `0, N-1`     | `lo > hi`    | 符合：`hi = mid - 1` 不符：`lo = mid + 1` | 符合：`lo = mid + 1` 不符：`hi = mid - 1` |
 * | **左闭右开 `[lo, hi)`** | `0, N`       | `lo == hi`   | **符合：`hi = mid`** 不符：`lo = mid + 1` | 此写法不常用于找“最后”                    |
 * | **左开右闭 `(lo, hi]`** | `-1, N-1`    | `lo == hi`   | 此写法不常用于找“第一”                    | **符合：`lo = mid`** 不符：`hi = mid - 1` |
 *
 * 逐轮手算表（用同一组有序数据，把三种写法并排看）
 * 假设数组仍然是：
 *   [Amy, Bob, David, Eva, Frank]
 * 对应下标：
 *   [ 0 ,  1 ,   2  ,  3 ,   4  ]
 *
 * 一、闭区间 [lo, hi]：查“David 在不在？”
 *   轮次 | lo | hi | mid | students[mid] | 动作
 *   -----+----+----+-----+---------------+----------------------------
 *     1  | 0  | 4  |  2  | David         | 命中，直接返回 2
 *
 * 二、左闭右开 [lo, hi)：查“第一个不小于 David 的位置在哪？”
 *   轮次 | lo | hi | mid | students[mid] | 动作
 *   -----+----+----+-----+---------------+----------------------------
 *     1  | 0  | 5  |  2  | David         | 已经不小于 David，hi = 2
 *     2  | 0  | 2  |  1  | Bob           | Bob < David，lo = 2
 *   结束 | 2  | 2  |  -  | -             | 答案是 2
 *
 * 三、左开右闭 (lo, hi]：查“最后一个不大于 Carl 的位置在哪？”
 *   由于我们要找的是“最后一个”，这意味着即便当前 mid 指向的元素已经符合条件（≤Carl）
 *   它的右边可能还存在另一个同样符合条件的元素。
 *
 *   轮次 | lo | hi | mid | students[mid] | 动作
 *   -----+----+----+-----+---------------+----------------------------
 *     1  | -1 | 4  |  2  | David         | David > Carl，hi = 1 (注意, 所有**可能**成为答案的下标必须处于 `(lo, hi]` 范围内。)
 *     2  | -1 | 1  |  0  | Amy           | Amy <= Carl，lo = 0
 *     3  | 0  | 1  |  1  | Bob           | Bob <= Carl，lo = 1
 *   结束 | 1  | 1  |  -  | -             | 答案是 1（Bob）
 *
 * 二分查找极值坍缩与取整方向的因果链路
 *
 * 当搜索区间坍缩至仅剩两个相邻元素 (hi - lo == 1) 时，
 * mid 的取整方向和边界的更新动作，完全由【搜索目标的物理语义】严格决定。
 *
 * 核心推导原则：目标语义 -> 决定测试优先级 -> 决定取整方向 -> 决定边界如何收缩
 *
 * [场景一] 寻找左边界 (第一个满足条件的位置)
 * - 语义目标：寻找最靠左的解。
 * - 测试优先：在 L=1 时，必须优先测试左端点 lo。
 * - 取整必然：为使 mid 指向 lo，必须采用【向下取整】：mid = lo + (hi - lo) / 2
 * - 状态转移：若 mid(即 lo) 满足条件，说明找到了目标。
 * 为使区间坍缩，必须将对侧的无关边界 hi 拉向目标：执行 hi = mid。
 * (这自然打破了 hi 的旧状态，避免了死循环)
 *
 * [场景二] 寻找右边界 (最后一个满足条件的位置)
 * - 语义目标：寻找最靠右的解。
 * - 测试优先：在 L=1 时，必须优先测试右端点 hi。
 * - 取整必然：为使 mid 指向 hi，必须采用【向上取整】：mid = lo + (hi - lo + 1) / 2
 * - 状态转移：若 mid(即 hi) 满足条件，说明找到了目标。
 * 为使区间坍缩，必须将对侧的无关边界 lo 拉向目标：执行 lo = mid。
 * (这自然打破了 lo 的旧状态，避免了死循环)
 *
 * ---------------------------------------------------------
 * 架构洞见与物理检验 (Sanity Check)
 * ---------------------------------------------------------
 * 1. 代数防线：死循环的本质是发生了用变量覆盖其自身的无效动作 (如 lo = lo)。
 * 只要 mid 准确坍缩向我们优先测试的端点，并在命中后拉扯对侧边界， 死循环就不会发生
 *
 * 2. 空间受力法则：在数轴拓扑上，边界推移的动量方向，必须与取整偏移的方向严格对齐。
 * - 右边界向左压 (←) ，意味着空间向左坍缩，必配向左的向下取整 (←)。
 * - 左边界向右抬 (→) ，意味着空间向右坍缩，必配向右的向上取整 (→)。
 * (这一物理直觉可作为写代码时的肌肉记忆断言)
 *
 * ---------------------------------------------------------
 * 溢出保护与基址偏移 (Overflow Protection & Base Offset)
 * ---------------------------------------------------------
 * 最好不要使用 (lo + hi) / 2。当 lo 和 hi 逼近整型上限 (如 INT_MAX) 时，
 * 两个绝对坐标直接相加会触发整数溢出 (Integer Overflow)，导致符号位翻转。
 *
 * ：将“绝对坐标的折半”转化为“基址 + 相对偏移量”。
 * 在底层的内存寻址和指针运算中，计算跨度 (hi - lo) 永远是安全的。
 * - 向下取整范式：mid = lo + ((hi - lo) >> 1)
 * - 向上取整范式：mid = lo + ((hi - lo + 1) >> 1)
 *
 * 注记：除了防御溢出，使用减法和右移 (>> 1) 明确了位级截断语义。
 * 当涉及左开右闭的 lo = -1 边界时，(hi - lo) 仍能保证为正数，
 * 此时算术右移的行为与向下取整的数学定义完全一致，规避了 C 语言中
 * 负数除法向零取整 (Truncate toward zero) 带来的未定义行为风险。
 *
 * ----------------------------------------------------------------------------------------
 * 二分查找不是某一个具体模板，而是一种利用有序性 / 单调性不断缩小候选范围的思维方式。
 *
 * 只要你能给问题建立顺序，并且能让一个判断随着位置单调变化，那你就收获了一种更普遍的搜索观
 * ----------------------------------------------------------------------------------------
 * 广义二分：从数据寻址到状态空间坍缩 (Generalized State Space Search)
 * ----------------------------------------------------------------------------------------
 * 二分的物理载体不局限于内存中的连续数组。只要状态空间存在某种拓扑单调性，
 * 使得某个布尔判定函数 P(x) 的结果呈现 [0, 0...0, 1...1, 1] 的阶跃，二分就成立。
 * * 1. 非理想单调环境下的降维架构 (System-Level Fallbacks)
 * 在实际底层架构中，全局连续有序往往成本极高。工程上通常采用“两阶段路由”来制造局部二分条件：
 * - 局部单调 (Local Monotonicity)：全局无序，但分块有序。
 *   例如 B+Tree / SSTable，外层机制通过稀疏索引 (Sparse Index) 将目标路由到特定的 Block/Page， 随后在 Block 内部的有序字节流上执行原生二分。
 * - 分段单调 (Piece-wise Monotonicity)：时间序列或日志流。
 *   先依据时间戳元数据锁定物理分段，将问题收敛至段内单调区间，再执行二分边界搜索。
 * * 2. 参数化搜索 (Parametric Search)：将最优化转化为判定
 * 在量化系统或资源调度中，直接求解“最大化利润”或“最优延迟”往往缺乏导数，无从下手。
 * 但如果将目标参数设为 x，判定问题“在阈值 x 的约束下，系统策略是否存活/合法”通常是严格单调的。
 * - 此时，搜索对象从“数组下标”变成了“抽象的参数轴”。
 * - 原本的高维最优化问题，被降维成了在一维空间上对 P(x) = true 的边界搜索。
 *
 * ---------------------------------------------------------
 * 广义二分架构设计核心协议 (Design Protocol)
 * ---------------------------------------------------------
 *
 * 剥离掉所有具体业务后，设计一个广义二分机制只需严格履行以下四步协议：
 * * - 定义状态空间 (Define Domain)：明确搜索对象是 LBA 扇区、版本号、还是抽象的资源上限。
 * - 构造单调谓词 (Construct Predicate)：设计布尔函数 P(x)，并在数学上证明其随 x 变化
 * 必然且仅产生一次 0 -> 1 或 1 -> 0 的状态跃变。
 * - 锚定不变量 (Anchor Invariant)：基于 P(x) 的跃变方向和业务需求，复用前文的“因果链路”，
 * 严格敲定区间开闭、测试优先级与取整方向。
 * - 执行拓扑坍缩 (Execute Collapse)：通过 O(log N) 的探测代价，利用判定结果强制排斥
 * 无效空间，直到系统状态坍缩至唯一的物理边界点。
 * * 结论：二分的工程难点永远不在于那十几行 while 循环，而在于你是否有能力在混沌的
 * 业务逻辑中，准确剥离出一个单调的布尔谓词 P(x)。谓词一旦确立，边界收缩只是物理必然。
 */

// 学生结构体
typedef struct {
    char name[NAME_LEN];
    int score;
} Student;

Student students[MAX_STUDENTS];
int n;

int binary_search(const char *target_name) {
    int lo = 0;
    int hi = n - 1;

    // 不变量：如果 target_name 存在，那么它一定还在闭区间 [lo, hi] 中。
    while (lo <= hi) {
        // 每轮重新计算 mid。写成 lo + (hi - lo) / 2 是标准写法。
        int mid = lo + (hi - lo) / 2;
        int cmp = strcmp(students[mid].name, target_name);

        if (cmp == 0) {
            // 命中就结束：这个函数只要求找到一个匹配位置。
            return mid;
        } else if (cmp < 0) {
            // students[mid].name < target_name
            // 说明 mid 以及它左边都不可能再命中，候选区间收缩为右半边。
            lo = mid + 1;
        } else {
            // students[mid].name > target_name
            // 说明 mid 以及它右边都不可能再命中，候选区间收缩为左半边。
            hi = mid - 1;
        }
    }

    // 走到这里，说明闭区间已经被收缩为空，目标不存在。
    return -1;
}

int main(void) {
    // 打开文件读取已排序的学生信息
    FILE *file = fopen("05_students.txt", "r");
    if (!file) {
        printf("错误：无法打开文件 05_students.txt\n");
        return 1;
    }

    // 读取学生人数
    fscanf(file, "%d", &n);
    if (n <= 0 || n > MAX_STUDENTS) {
        printf("学生人数无效：%d\n", n);
        fclose(file);
        return 1;
    }

    // 读取每个学生信息
    for (int i = 0; i < n; i++) {
        fscanf(file, "%s %d", students[i].name, &students[i].score);
    }
    fclose(file);

    char query_name[NAME_LEN] = "David";

    int index = binary_search(query_name);

    printf("\n折半查找出的排序后的学生信息：\n");
    if (index != -1) {
        printf("姓名：%s，成绩：%d\n", students[index].name, students[index].score);
    } else {
        printf("未找到该学生\n");
    }

    return 0;
}
